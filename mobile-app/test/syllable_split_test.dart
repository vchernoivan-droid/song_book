import 'package:flutter_test/flutter_test.dart';
import 'package:song_book/services/syllable_split.dart';

void main() {
  void check(String word, List<String> expected) {
    test(word, () {
      expect(splitWordToSyllables(word), expected);
    });
  }

  group('открытые слоги', () {
    check('мама', ['ма', 'ма']);
    check('молоко', ['мо', 'ло', 'ко']);
    check('корова', ['ко', 'ро', 'ва']);
    check('осень', ['о', 'сень']);
    check('музыка', ['му', 'зы', 'ка']);
    check('зеркало', ['зер', 'ка', 'ло']);
    check('хорошо', ['хо', 'ро', 'шо']);
    check('люди', ['лю', 'ди']);
    check('юла', ['ю', 'ла']);
    check('эхо', ['э', 'хо']);
  });

  group('й, ь, ъ закрывают слог', () {
    check('война', ['вой', 'на']);
    check('район', ['рай', 'он']);
    check('шайба', ['шай', 'ба']);
    check('стройка', ['строй', 'ка']);
    check('пальма', ['паль', 'ма']);
    check('мальчик', ['маль', 'чик']);
    check('только', ['толь', 'ко']);
    check('подъезд', ['подъ', 'езд']);
    check('объезд', ['объ', 'езд']);
    check('субъект', ['субъ', 'ект']);
    check('съеду', ['съе', 'ду']);
    check('съел', ['съел']);
  });

  group('максимальное начало слога', () {
    check('весна', ['ве', 'сна']);
    check('история', ['и', 'сто', 'ри', 'я']);
    check('конструкция', ['кон', 'струк', 'ци', 'я']);
    check('облако', ['о', 'бла', 'ко']);
    check('сестра', ['се', 'стра']);
    check('родство', ['род', 'ство']);
    check('асфальт', ['а', 'сфальт']);
    check('переплетать', ['пе', 'ре', 'пле', 'тать']);
    check('воскресенье', ['во', 'скре', 'се', 'нье']);
    check('счастье', ['сча', 'стье']);
    check('здравствуй', ['здрав', 'ствуй']);
  });

  group('границы скоплений', () {
    check('касса', ['кас', 'са']);
    check('ванна', ['ван', 'на']);
    check('рассказ', ['рас', 'сказ']);
    check('мощность', ['мощ', 'ность']);
    check('конечный', ['ко', 'неч', 'ный']);
    check('полный', ['пол', 'ный']);
  });

  group('гласные подряд', () {
    check('мая', ['ма', 'я']);
    check('поёт', ['по', 'ёт']);
    check('театр', ['те', 'атр']);
    check('строить', ['стро', 'ить']);
    check('июнь', ['и', 'юнь']);
    check('аура', ['а', 'у', 'ра']);
    check('оазис', ['о', 'а', 'зис']);
  });

  group('песенные слова', () {
    check('любимая', ['лю', 'би', 'ма', 'я']);
    check('калина', ['ка', 'ли', 'на']);
    check('переходит', ['пе', 'ре', 'хо', 'дит']);
    check('пьеса', ['пье', 'са']);
  });

  group('краевые случаи', () {
    check('ёж', ['ёж']);
    check('а', ['а']);
    check('хм', ['хм']);
    check('', ['']);
    check('the', ['the']);
    check('МОЛОКО', ['МО', 'ЛО', 'КО']);
    check('Осень', ['О', 'сень']);
    check('Ёлка', ['Ёл', 'ка']);
    check('Родина', ['Ро', 'ди', 'на']);
  });

  test('слоги в сумме дают исходное слово', () {
    const words = [
      'молоко', 'подъезд', 'конструкция', 'поёт', 'Ёлка', 'любимая',
      'переходит', 'сестра', 'облако', 'мальчик', 'июнь', 'театр',
      'воскресенье', 'счастье', 'здравствуй', 'рассказ',
    ];
    for (final w in words) {
      expect(splitWordToSyllables(w).join(), w, reason: w);
    }
  });
}
